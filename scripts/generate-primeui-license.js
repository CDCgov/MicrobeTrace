const fs = require('node:fs');
const path = require('node:path');
const process = require('node:process');

const repoRoot = path.resolve(__dirname, '..');
const localEnvPath = path.join(repoRoot, '.env.local');
const outputPath = path.join(repoRoot, 'src', 'environments', 'primeui-license.generated.ts');
const isRequired = process.argv.includes('--required');

if (!process.env.PRIMEUI_LICENSE_KEY && fs.existsSync(localEnvPath)) {
  process.loadEnvFile(localEnvPath);
}

const licenseKey = process.env.PRIMEUI_LICENSE_KEY?.trim() ?? '';

if (!licenseKey && isRequired) {
  console.error(
    'PRIMEUI_LICENSE_KEY is required to build the deployable WAR. ' +
      'Set it in the build environment or in the ignored .env.local file.'
  );
  process.exit(1);
}

const generatedSource = `// Generated by scripts/generate-primeui-license.js. Do not commit this file.\n` +
  `export const primeUiLicenseKey = ${JSON.stringify(licenseKey)};\n`;

fs.writeFileSync(outputPath, generatedSource, 'utf8');

if (licenseKey) {
  console.log('Prepared the PrimeUI license configuration.');
} else {
  console.warn(
    'PRIMEUI_LICENSE_KEY is not set. PrimeNG may display a development license notice. ' +
      'Copy .env.local.example to .env.local and add the key.'
  );
}
